#!/usr/bin/env python3
"""Create presentation-ready figures from Demo 2 evaluation CSV summaries.

Usage on Markov (after activating the existing virtual environment):
    cd ~/447_demo2
    python plot_evaluation_results.py --results-dir results

Input (generated by summarize_evaluation.py):
    results/evaluation/summary/overall_summary.csv
    results/evaluation/summary/per_seed_summary.csv (optional fallback for SD)

Output:
    results/evaluation/plots/*.png

No HF downloads or GPU necessary. Supports the four model/dataset families,
4 Cheng baselines, and 5 independently seeded samples/question.

Interpretation:
- Exact-match "accuracy" is SQuAD-style normalized string match, not a
  semantic truth label. QASPER token F1 is answer-only, not evidence F1.
- Judge TRUE rate is the proportion of *parsed* self-judgments labeled TRUE.
  It is not independent accuracy and may use a different denominator from EM.
- Seed error bars depict between-sample-seed SD, not dataset bootstrap CIs.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys
import warnings

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.patches import Patch
import numpy as np
import pandas as pd

BASELINES = ["vanilla", "structured", "p_true", "initial_test"]
BASELINE_NAMES = {
    "vanilla": "Standard self-report",
    "structured": "Structured self-report",
    "p_true": "P(True) answer",
    "initial_test": "Overconfidence warning",
}
MODEL_NAMES = {
    "meta-llama/Llama-3.2-1B-Instruct": "Llama 1B",
    "meta-llama/Llama-3.2-3B-Instruct": "Llama 3B",
    "Qwen/Qwen3-1.7B": "Qwen 1.7B",
    "Qwen/Qwen3-4B": "Qwen 4B",
}
MODEL_ORDER = ["Llama 1B", "Llama 3B", "Qwen 1.7B", "Qwen 4B"]
DATASETS = ["SciQ", "QASPER"]


def find_input(name: str, results_dir: Path) -> Path | None:
    """Use documented output first; support alternate summary locations."""
    possibilities = [
        results_dir / "evaluation" / "summary" / name,
        results_dir / "evaluation" / name,
        results_dir / "summary" / name,
        results_dir / name,
    ]
    return next((p for p in possibilities if p.is_file()), None)


def load_tables(results_dir: Path) -> tuple[pd.DataFrame, pd.DataFrame | None]:
    overall_path = find_input("overall_summary.csv", results_dir)
    if overall_path is None:
        paths = "\n  ".join(str(p) for p in [
            results_dir / "evaluation" / "summary" / "overall_summary.csv",
            results_dir / "overall_summary.csv",
        ])
        raise FileNotFoundError(f"Could not find overall_summary.csv. Checked:\n  {paths}")

    overall = pd.read_csv(overall_path)
    needed = {
        "model", "dataset", "baseline", "accuracy_exact_match", "token_f1",
        "judge_true_rate", "judge_parse_rate", "mean_judge_confidence_1to10",
        "judge_agreement_with_exact_match",
    }
    missing = needed - set(overall.columns)
    if missing:
        raise ValueError(f"{overall_path}: missing columns: {sorted(missing)}")

    seed_path = find_input("per_seed_summary.csv", results_dir)
    seeds = pd.read_csv(seed_path) if seed_path else None
    for df in [overall, seeds]:
        if df is None:
            continue
        df["model_label"] = df["model"].map(MODEL_NAMES).fillna(
            df["model"].astype(str).str.rsplit("/", n=1).str[-1]
        )
        df["dataset"] = df["dataset"].astype(str).str.upper().map(
            {"SCIQ": "SciQ", "QASPER": "QASPER"}
        ).fillna(df["dataset"])
        df["baseline"] = df["baseline"].astype(str)

    # One aggregate row per model/dataset/baseline is expected.
    keys = ["model", "dataset", "baseline"]
    if overall.duplicated(keys).any():
        raise ValueError("overall_summary.csv contains duplicate model/dataset/baseline rows")

    sd_cols = {
        "accuracy_exact_match": "sample_seed_sd_accuracy",
        "token_f1": "sample_seed_sd_f1",
    }
    if seeds is not None:
        for metric, sd_col in sd_cols.items():
            if sd_col not in overall.columns or overall[sd_col].isna().all():
                sd = (
                    seeds.groupby(keys, dropna=False)[metric]
                    .std(ddof=1)
                    .rename(sd_col)
                    .reset_index()
                )
                overall = overall.drop(columns=[sd_col], errors="ignore").merge(
                    sd, on=keys, how="left"
                )
    return overall, seeds


def ordered_models(df: pd.DataFrame) -> list[str]:
    present = set(df["model_label"].unique())
    return [m for m in MODEL_ORDER if m in present] + sorted(present - set(MODEL_ORDER))


def format_plot(fig: plt.Figure, output: Path, pdf: bool) -> None:
    fig.savefig(output, dpi=180, bbox_inches="tight", facecolor="white")
    if pdf:
        fig.savefig(output.with_suffix(".pdf"), bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print(f"Saved {output}")


def plot_metric_by_dataset(
    df: pd.DataFrame, dataset: str, metric: str, sd_col: str,
    title: str, filename: str, output_dir: Path, pdf: bool
) -> None:
    dat = df[df["dataset"] == dataset].copy()
    if dat.empty:
        return
    models = ordered_models(dat)
    idx = pd.MultiIndex.from_product([models, BASELINES], names=["model_label", "baseline"])
    table = dat.set_index(["model_label", "baseline"]).reindex(idx)
    x = np.arange(len(models), dtype=float)
    width = 0.195
    fig, ax = plt.subplots(figsize=(10.7, 5.8))
    for i, baseline in enumerate(BASELINES):
        subset = table.xs(baseline, level="baseline").reindex(models)
        y = pd.to_numeric(subset[metric], errors="coerce").to_numpy(dtype=float) * 100
        if sd_col in subset:
            yerr = pd.to_numeric(subset[sd_col], errors="coerce").fillna(0).to_numpy(dtype=float) * 100
        else:
            yerr = np.zeros_like(y)
        offset = (i - (len(BASELINES) - 1) / 2) * width
        ax.bar(x + offset, y, width, yerr=yerr, capsize=2.5,
               label=BASELINE_NAMES[baseline], error_kw={"elinewidth": 1.0})

    ax.set_xticks(x, models)
    ax.set_ylim(0, 105)
    ax.set_ylabel("Score (%)")
    ax.set_title(f"{dataset} | {title}", weight="bold", pad=16)
    ax.grid(axis="y", alpha=0.18)
    ax.set_axisbelow(True)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.12), ncol=2, frameon=False)
    fig.text(0.5, 0.01,
             "Error bars = SD across 5 answer-sample seeds (not independent dataset-run CIs)",
             ha="center", va="bottom", fontsize=9)
    fig.subplots_adjust(bottom=0.25, top=0.88)
    format_plot(fig, output_dir / filename, pdf)


def plot_judge_vs_match(df: pd.DataFrame, dataset: str, output_dir: Path, pdf: bool) -> None:
    dat = df[df["dataset"] == dataset].copy()
    if dat.empty:
        return
    models = ordered_models(dat)
    colors = plt.rcParams["axes.prop_cycle"].by_key()["color"]
    markers = {"vanilla": "o", "structured": "s", "p_true": "^", "initial_test": "D"}
    fig, ax = plt.subplots(figsize=(8.4, 7))
    for i, model in enumerate(models):
        for b in BASELINES:
            ss = dat[(dat["model_label"] == model) & (dat["baseline"] == b)]
            if ss.empty:
                continue
            row = ss.iloc[0]
            x = float(row["accuracy_exact_match"]) * 100
            y = float(row["judge_true_rate"]) * 100
            if not (np.isfinite(x) and np.isfinite(y)):
                continue
            ax.scatter(x, y, s=110, marker=markers[b], color=colors[i % len(colors)],
                       alpha=0.85, edgecolor="white", linewidth=0.6, zorder=3)
            # Label vanilla once for each model; full identities are in legends.
            if b == "vanilla":
                ax.annotate(model, (x, y), xytext=(6, 5), textcoords="offset points", fontsize=8)

    ax.plot([0, 100], [0, 100], ls="--", color="gray", alpha=0.75, linewidth=1,
            label="Equal rates (reference)")
    ax.set(xlim=(-3, 103), ylim=(-3, 103), xlabel="Normalized exact match (%)",
           ylabel="Self-judge TRUE rate among parsed judgments (%)")
    ax.set_title(f"{dataset} | Self-judge positivity vs reference match", weight="bold", pad=15)
    ax.grid(alpha=0.18)
    color_handles = [Line2D([], [], marker="o", linestyle="none", color=colors[i % len(colors)],
                            label=m, markersize=8) for i, m in enumerate(models)]
    baseline_handles = [Line2D([], [], marker=markers[b], linestyle="none", color="gray",
                               label=BASELINE_NAMES[b], markersize=7) for b in BASELINES]
    legend1 = ax.legend(handles=color_handles, title="Model", loc="upper left", fontsize=8,
                        title_fontsize=9)
    ax.add_artist(legend1)
    ax.legend(handles=baseline_handles, title="Baseline", loc="lower right", fontsize=8,
              title_fontsize=9)
    fig.text(0.5, 0.012,
             "TRUE rate uses valid judgments; exact match uses evaluable answers. Gaps do not prove judging errors.",
             ha="center", fontsize=8.5)
    fig.subplots_adjust(bottom=0.10)
    format_plot(fig, output_dir / f"judge_vs_exact_{dataset.lower()}.png", pdf)


def plot_parse_heatmap(df: pd.DataFrame, out: Path, pdf: bool) -> None:
    from matplotlib.colors import Normalize
    from matplotlib.cm import ScalarMappable
    present_ds = [d for d in DATASETS if d in df["dataset"].unique()]
    models = ordered_models(df)
    rows = [(d, m) for d in present_ds for m in models]
    data = np.full((len(rows), len(BASELINES)), np.nan)
    for i, (ds, model) in enumerate(rows):
        for j, baseline in enumerate(BASELINES):
            match = df[(df["dataset"] == ds) & (df["model_label"] == model)
                       & (df["baseline"] == baseline)]
            if len(match):
                data[i, j] = float(match.iloc[0]["judge_parse_rate"]) * 100

    fig, ax = plt.subplots(figsize=(10.4, max(5.5, 0.75 * len(rows) + 1.6)))
    cmap = plt.get_cmap("viridis").copy()
    cmap.set_bad("lightgray")
    masked = np.ma.masked_invalid(data)
    im = ax.imshow(masked, cmap=cmap, vmin=0, vmax=100, aspect="auto")
    ax.set_xticks(range(len(BASELINES)), [BASELINE_NAMES[b] for b in BASELINES], rotation=22, ha="right")
    ax.set_yticks(range(len(rows)), [f"{m} / {d}" for d, m in rows])
    ax.set_title("LLM-as-a-Judge | Valid verdict parsing coverage", weight="bold", pad=13)
    for i in range(len(rows)):
        for j in range(len(BASELINES)):
            v = data[i, j]
            if np.isfinite(v):
                ax.text(j, i, f"{v:.1f}%", ha="center", va="center",
                        color="white" if v < 55 else "black", fontsize=10)
    cbar = fig.colorbar(im, ax=ax, shrink=0.84, pad=0.025)
    cbar.set_label("Valid judge verdicts / attempted judgments (%)")
    fig.tight_layout()
    format_plot(fig, out / "judge_parse_coverage.png", pdf)


def plot_baseline_changes(df: pd.DataFrame, metric: str, title: str,
                          filename: str, out: Path, pdf: bool) -> None:
    """Compare each method's metric against the standard-self-report baseline."""
    baselines = ["structured", "p_true", "initial_test"]
    models = ordered_models(df)
    rows = [(ds, m) for ds in DATASETS for m in models if not df[(df["dataset"] == ds) &
                                                                  (df["model_label"] == m)].empty]
    arr = np.full((len(rows), len(baselines)), np.nan)
    for i, (ds, model) in enumerate(rows):
        sub = df[(df["dataset"] == ds) & (df["model_label"] == model)].set_index("baseline")
        if "vanilla" not in sub.index:
            continue
        v = float(sub.loc["vanilla", metric])
        for j, b in enumerate(baselines):
            if b in sub.index:
                arr[i, j] = (float(sub.loc[b, metric]) - v) * 100
    finite = arr[np.isfinite(arr)]
    lim = max(5, np.ceil(np.max(np.abs(finite)) / 5) * 5) if finite.size else 10
    fig, ax = plt.subplots(figsize=(9.8, max(5.5, len(rows) * .70 + 1.5)))
    cm = plt.get_cmap("coolwarm").copy()
    cm.set_bad("lightgray")
    im = ax.imshow(np.ma.masked_invalid(arr), cmap=cm, vmin=-lim, vmax=lim, aspect="auto")
    ax.set_yticks(range(len(rows)), [f"{m} / {ds}" for ds, m in rows])
    ax.set_xticks(range(len(baselines)), [BASELINE_NAMES[b] for b in baselines], rotation=15, ha="right")
    ax.set_title(title, weight="bold", pad=14)
    for i in range(len(rows)):
        for j in range(len(baselines)):
            if np.isfinite(arr[i, j]):
                ax.text(j, i, f"{arr[i,j]:+.1f} pp", ha="center", va="center", fontsize=10,
                        color="white" if abs(arr[i,j]) > lim * 0.65 else "black")
    cbar = fig.colorbar(im, ax=ax, shrink=.82, pad=0.025)
    cbar.set_label("Change versus standard self-report (percentage points)")
    fig.tight_layout()
    format_plot(fig, out / filename, pdf)


def plot_judge_confidence_vs_agreement(df: pd.DataFrame, out: Path, pdf: bool) -> None:
    models = ordered_models(df)
    colors = plt.rcParams["axes.prop_cycle"].by_key()["color"]
    ds_markers = {"SciQ": "o", "QASPER": "^"}
    fig, ax = plt.subplots(figsize=(9.3, 6.2))
    for i, model in enumerate(models):
        for ds in DATASETS:
            ss = df[(df["model_label"] == model) & (df["dataset"] == ds)]
            if ss.empty:
                continue
            x = pd.to_numeric(ss["mean_judge_confidence_1to10"], errors="coerce")
            y = pd.to_numeric(ss["judge_agreement_with_exact_match"], errors="coerce") * 100
            ax.scatter(x, y, color=colors[i % len(colors)], marker=ds_markers[ds],
                       alpha=.75, s=100, edgecolor="white", linewidth=.6)
    ax.set(xlim=(1, 10.3), ylim=(-3, 103), xlabel="Mean self-judge confidence (1–10)",
           ylabel="Agreement with normalized exact match (%)")
    ax.grid(alpha=.2)
    ax.set_title("Self-judge confidence versus reference-match agreement", weight="bold", pad=14)
    h_models = [Line2D([], [], color=colors[i % len(colors)], marker="o", linestyle="none",
                       label=m, markersize=8) for i, m in enumerate(models)]
    h_ds = [Line2D([], [], color="gray", marker=ds_markers[d], linestyle="none",
                   label=d, markersize=8) for d in DATASETS]
    leg = ax.legend(handles=h_models, title="Model", loc="lower left", fontsize=9)
    ax.add_artist(leg)
    ax.legend(handles=h_ds, title="Dataset", loc="upper left", fontsize=9)
    fig.text(.5, .012, "Agreement is with an exact-match proxy, not verified semantic correctness.",
             ha="center", fontsize=9)
    fig.subplots_adjust(bottom=.12)
    format_plot(fig, out / "judge_confidence_vs_agreement.png", pdf)


def print_key_checks(df: pd.DataFrame) -> None:
    print("\nEVALUATION INPUT CHECKS")
    print(f"  Rows: {len(df)}; expected 32 for 4 models × 2 datasets × 4 baselines")
    if len(df) != 32:
        warnings.warn(f"Expected 32 rows; got {len(df)}. Some comparisons may be incomplete.")
    for _, r in df[df["judge_parse_rate"] < .90].sort_values("judge_parse_rate").iterrows():
        print(f"  CAUTION: judge parse coverage {r['judge_parse_rate']:.1%}: "
              f"{r['model_label']} / {r['dataset']} / {r['baseline']}")
    v = df.loc[df["baseline"] == "vanilla", ["model_label", "dataset", "accuracy_exact_match", "token_f1"]]
    print("\nVanilla baseline (reference metrics):")
    print(v.to_string(index=False, float_format=lambda x: f"{x:.3f}"))


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results-dir", type=Path, default=Path("results"),
                   help="Project results folder (default: results)")
    p.add_argument("--output-dir", type=Path, default=None,
                   help="Default: <results-dir>/evaluation/plots")
    p.add_argument("--pdf", action="store_true", help="Also save vector PDF figures")
    args = p.parse_args()
    output_dir = args.output_dir or (args.results_dir / "evaluation" / "plots")
    output_dir.mkdir(parents=True, exist_ok=True)

    plt.rcParams.update({"font.size": 10.5, "axes.titlesize": 14, "axes.labelsize": 11,
                         "figure.dpi": 110, "savefig.dpi": 180})
    data, seeds = load_tables(args.results_dir)
    print_key_checks(data)
    for ds in DATASETS:
        for metric, sd_col, title, filename in [
            ("accuracy_exact_match", "sample_seed_sd_accuracy", "Normalized exact-match accuracy",
             f"accuracy_{ds.lower()}.png"),
            ("token_f1", "sample_seed_sd_f1", "Answer token F1",
             f"token_f1_{ds.lower()}.png"),
        ]:
            plot_metric_by_dataset(data, ds, metric, sd_col, title, filename,
                                   output_dir, args.pdf)
        plot_judge_vs_match(data, ds, output_dir, args.pdf)
    plot_parse_heatmap(data, output_dir, args.pdf)
    plot_baseline_changes(data, "accuracy_exact_match", "Exact match | Baseline effect vs standard self-report",
                          "baseline_delta_accuracy.png", output_dir, args.pdf)
    plot_baseline_changes(data, "token_f1", "Token F1 | Baseline effect vs standard self-report",
                          "baseline_delta_token_f1.png", output_dir, args.pdf)
    plot_judge_confidence_vs_agreement(data, output_dir, args.pdf)
    print("\nAll charts saved to:", output_dir.resolve())
    if seeds is None:
        print("NOTE: per_seed_summary.csv missing; error bars use SD columns in overall_summary.csv if present.")


if __name__ == "__main__":
    main()
