def normalize_question(q):
    """
    Strips extra prompt instruction lines following newlines (\n)
    and normalizes spacing/casing for cross-file alignment.
    """
    if pd.isna(q):
        return ""
    q_first_line = str(q).split('\n')[0].strip()
    return re.sub(r'\s+', ' ', q_first_line.lower())


def extract_first_valid_num(val):
    """Extracts the first valid numerical float from pipe-delimited strings."""
    if pd.isna(val):
        return np.nan
    val_str = str(val).strip()
    
    parts = [p.strip() for p in val_str.split('||')]
    for p in parts:
        try:
            clean_p = re.sub(r'[^\d.-]', '', p)
            if clean_p != '' and clean_p != '-':
                return float(clean_p)
        except (ValueError, TypeError):
            continue
    return np.nan


def compute_rouge_l_f1(reference, candidate):
    """
    Computes word-token Longest Common Subsequence (LCS) ROUGE-L F1 score
    and returns (F1, perfect_recall) boolean flag.
    """
    if pd.isna(reference) or pd.isna(candidate):
        return 0.0, False
    
    ref_tokens = str(reference).strip().lower().split()
    cand_tokens = str(candidate).strip().lower().split()
        
    m, n = len(ref_tokens), len(cand_tokens)
    if m == 0 or n == 0:
        return 0.0, False
    
    dp = [[0] * (n + 1) for _ in range(m + 1)]
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            if ref_tokens[i - 1] == cand_tokens[j - 1]:
                dp[i][j] = dp[i - 1][j - 1] + 1
            else:
                dp[i][j] = max(dp[i - 1][j], dp[i][j - 1])
                
    lcs_len = dp[m][n]
    precision = lcs_len / n
    recall = lcs_len / m
    
    if precision + recall == 0:
        return 0.0, False
    return (2 * precision * recall) / (precision + recall), (recall == 1.0)


def compute_auroc(y_true, scores, is_entropy=True):
    """Computes Area Under ROC Curve (AUROC). Entropy is negated so lower entropy = higher confidence."""
    y_true_arr = np.asarray(pd.to_numeric(y_true, errors='coerce'))
    scores_arr = np.asarray(pd.to_numeric(scores, errors='coerce'))

    valid_idx = ~np.isnan(scores_arr) & ~np.isnan(y_true_arr)
    y_true_arr, scores_arr = y_true_arr[valid_idx], scores_arr[valid_idx]

    if len(y_true_arr) == 0:
        return np.nan

    y_binary = (y_true_arr >= 0.5).astype(int)

    if len(np.unique(y_binary)) < 2:
        return np.nan

    conf_scores = -scores_arr if is_entropy else scores_arr
    return float(roc_auc_score(y_binary, conf_scores))


def compute_aurc(y_true, scores, is_entropy=True):
    """Computes Area Under Rejection Curve (AURC) / Area Under Accuracy-Coverage Curve."""
    y_true_arr = np.asarray(pd.to_numeric(y_true, errors='coerce'))
    scores_arr = np.asarray(pd.to_numeric(scores, errors='coerce'))

    valid_idx = ~np.isnan(scores_arr) & ~np.isnan(y_true_arr)
    y_true_arr, scores_arr = y_true_arr[valid_idx], scores_arr[valid_idx]

    n = len(y_true_arr)
    if n == 0:
        return np.nan

    y_binary = (y_true_arr >= 0.5).astype(float)

    conf_scores = -scores_arr if is_entropy else scores_arr
    sort_idx = np.argsort(-conf_scores)
    sorted_y = y_binary[sort_idx]

    coverages = np.linspace(1.0 / n, 1.0, n)
    accuracies = np.cumsum(sorted_y) / np.arange(1, n + 1)

    return float(trapz_fn(accuracies, coverages))


def match_sciq_model(filename, df_head=None):
    """Verifies file belongs to SciQ and determines canonical model key."""
    filename_lower = filename.lower()
    if "sciq" not in filename_lower:
        if df_head is not None and "dataset" in df_head.columns:
            if "sciq" not in str(df_head["dataset"].iloc[0]).lower():
                return None
        else:
            return None

    fn_clean = re.sub(r'[^a-z0-9]', '', filename_lower)

    model_key = None
    for canonical_key, aliases in MODEL_ALIASES.items():
        for alias in aliases:
            alias_clean = re.sub(r'[^a-z0-9]', '', alias)
            if alias_clean in fn_clean:
                model_key = canonical_key
                break
        if model_key:
            break

    return model_key


def filter_biased_incorrect(df):
    """
    Restricts DataFrame exclusively to the biased questions 
    (suggesting an incorrect answer / 2nd variant).
    """
    df_copy = df.copy()

    if 'bias_condition' in df_copy.columns:
        df_filtered = df_copy[df_copy['bias_condition'].astype(str).str.lower().str.contains('incorrect')].copy()
        if not df_filtered.empty:
            return df_filtered
    elif 'question_idx' in df_copy.columns and df_copy.duplicated(subset=['question_idx']).any():
        return df_copy.groupby('question_idx', as_index=False).nth(1)
    elif 'original_question' in df_copy.columns and df_copy.duplicated(subset=['original_question']).any():
        return df_copy.groupby('original_question', as_index=False).nth(1)
    elif len(df_copy) > 1 and len(df_copy) % 2 == 0:
        return df_copy.iloc[1::2].copy()

    return df_copy


def parse_confidence_df(df):
    """Parses confidence fields for biased SciQ question entries."""
    df_copy = filter_biased_incorrect(df)

    if "question" in df_copy.columns:
        df_copy["norm_question"] = df_copy["question"].apply(normalize_question)

    vanilla_col = next((c for c in ['vanilla_baseline_all_confidence', 'vanilia_baseline_all_confidence'] if c in df_copy.columns), None)
    if vanilla_col:
        df_copy['vanilla_self_report'] = df_copy[vanilla_col].apply(extract_first_valid_num)

    if 'structured_self-report_all_confidence' in df_copy.columns:
        df_copy['structured_self_report'] = df_copy['structured_self-report_all_confidence'].apply(extract_first_valid_num)

    p_true_col = next((c for c in ['p_true_probability_B', 'p_true_probability_A', 'p_true_probability'] if c in df_copy.columns), None)
    if p_true_col:
        df_copy['p_true_probability'] = df_copy[p_true_col].apply(extract_first_valid_num)

    return df_copy


def extract_correctness_from_df(df):
    """
    Filters evaluation DataFrame for biased SciQ entries and extracts correctness labels.
    """
    df_copy = filter_biased_incorrect(df)

    if "question" in df_copy.columns:
        df_copy["norm_question"] = df_copy["question"].apply(normalize_question)
    else:
        df_copy["norm_question"] = df_copy.index.astype(str)

    if "sample_index" in df_copy.columns:
        df_copy = df_copy[df_copy["sample_index"] == 1]

    if "baseline" in df_copy.columns and "initial_test" in df_copy["baseline"].values:
        df_copy = df_copy[df_copy["baseline"] == "initial_test"]

    df_copy = df_copy.drop_duplicates(subset=["norm_question"])

    correctness_col = None
    for col in ["correctness", "judge_verdict", "judge_verdit", "exact_match", "token_f1"]:
        if col in df_copy.columns and not df_copy[col].isna().all():
            correctness_col = col
            break

    if correctness_col == "correctness":
        df_copy["correctness"] = pd.to_numeric(df_copy["correctness"], errors='coerce')
    elif correctness_col in ["judge_verdict", "judge_verdit"]:
        if "exact_match" in df_copy.columns:
            df_copy["correctness"] = df_copy[correctness_col].fillna(df_copy["exact_match"]).astype(float)
        else:
            df_copy["correctness"] = df_copy[correctness_col].astype(bool).astype(float)
    elif correctness_col == "exact_match":
        df_copy["correctness"] = df_copy["exact_match"].astype(float)
    elif correctness_col == "token_f1":
        df_copy["correctness"] = (df_copy["token_f1"] > 0.5).astype(float)
    else:
        df_copy["correctness"] = np.nan

    return df_copy[['norm_question', 'correctness']]


def load_sciq_metrics(entropy_dir, confidence_dir, evaluated_dir, fallback_dir=None, rouge_threshold=0.25):
    """
    Scans data directories exclusively for SciQ files, filters for biased questions,
    and computes mean and SEM (Standard Error of the Mean) across models.
    """
    metrics = {}
    entropy_bar_stats = {}

    search_dirs = [d for d in [fallback_dir, entropy_dir, confidence_dir, evaluated_dir] if d and os.path.exists(d)]
    all_files = []
    for d in search_dirs:
        all_files.extend(glob.glob(os.path.join(d, "*.csv")))

    entropy_map, confidence_map, evaluated_map = {}, {}, {}

    for f in set(all_files):
        filename = os.path.basename(f).lower()
        if "sciq" not in filename:
            continue

        try:
            df_temp = pd.read_csv(f, nrows=5)
        except Exception:
            continue

        mk = match_sciq_model(filename, df_temp)
        if not mk:
            continue

        is_eval_file = ("judge" in filename or "evaluated" in filename)

        if is_eval_file:
            evaluated_map[mk] = f
        elif any(col in df_temp.columns for col in ["semantic_entropy", "predictive_entropy"]) or "entropy" in filename:
            entropy_map[mk] = f
        elif any(col in df_temp.columns for col in ['vanilla_baseline_all_confidence', 'p_true_probability_B']) or "confidence" in filename or "combined" in filename:
            confidence_map[mk] = f

    all_models = set(entropy_map.keys()).union(set(confidence_map.keys())).union(set(evaluated_map.keys()))

    for mk in all_models:
        merged_df = pd.DataFrame()

        # 1. Load Entropy & Compute Mean/SEM for biased questions
        if mk in entropy_map:
            e_df = pd.read_csv(entropy_map[mk])
            e_df = filter_biased_incorrect(e_df)
            if "question" in e_df.columns:
                e_df["norm_question"] = e_df["question"].apply(normalize_question)
            merged_df = e_df

            stats = {}
            for col_key, _, _, _, _ in ENTROPY_MEASURES:
                if col_key in e_df.columns:
                    s_val = pd.to_numeric(e_df[col_key], errors='coerce')
                    stats[col_key] = (s_val.mean(), s_val.sem())
            entropy_bar_stats[mk] = stats

        # 2. Load Confidence
        if mk in confidence_map:
            c_df = pd.read_csv(confidence_map[mk])
            c_parsed = parse_confidence_df(c_df)
            
            if merged_df.empty:
                merged_df = c_parsed
            else:
                conf_cols = [c for c in ['vanilla_self_report', 'structured_self_report', 'p_true_probability'] if c in c_parsed.columns]
                if 'norm_question' in c_parsed.columns and 'norm_question' in merged_df.columns:
                    merged_df = pd.merge(merged_df, c_parsed[['norm_question'] + conf_cols], on='norm_question', how='inner')

        # 3. Load Evaluated Data & Compute ROUGE-L
        if mk in evaluated_map:
            raw_eval_df = pd.read_csv(evaluated_map[mk])
            raw_eval_df = filter_biased_incorrect(raw_eval_df)
            if "question" in raw_eval_df.columns:
                raw_eval_df["norm_question"] = raw_eval_df["question"].apply(normalize_question)

            ref_col = next((c for c in ["ground_truth", "correct_answer", "reference_answer"] if c in raw_eval_df.columns), None)
            cand_col = next((c for c in ["model_response", "model_answer", "response"] if c in raw_eval_df.columns), None)

            if ref_col and cand_col:
                raw_eval_df['rouge_l'], raw_eval_df['perfect_recall'] = zip(*[compute_rouge_l_f1(r, c) for r, c in zip(raw_eval_df[ref_col], raw_eval_df[cand_col])])
                raw_eval_df['rouge_l_correctness'] = ((raw_eval_df['rouge_l'] >= rouge_threshold) | (raw_eval_df['perfect_recall'])).astype(float)

            correctness_df = extract_correctness_from_df(raw_eval_df)
            if 'rouge_l' in raw_eval_df.columns and 'norm_question' in correctness_df.columns:
                r_sub = raw_eval_df[['norm_question', 'rouge_l', 'rouge_l_correctness']].drop_duplicates(subset=['norm_question'])
                correctness_df = pd.merge(correctness_df, r_sub, on='norm_question', how='inner')

            if merged_df.empty:
                merged_df = correctness_df
            elif 'norm_question' in merged_df.columns and 'norm_question' in correctness_df.columns:
                merged_df = pd.merge(merged_df, correctness_df, on='norm_question', how='inner')

        if merged_df.empty:
            continue

        if 'correctness' in merged_df.columns:
            s_judge = pd.to_numeric(merged_df['correctness'], errors='coerce')
            judge_acc, judge_sem = s_judge.mean(), s_judge.sem()
        else:
            judge_acc, judge_sem = np.nan, np.nan

        if 'rouge_l_correctness' in merged_df.columns:
            s_rouge = pd.to_numeric(merged_df['rouge_l_correctness'], errors='coerce')
            rouge_acc, rouge_sem = s_rouge.mean(), s_rouge.sem()
            mean_rouge = pd.to_numeric(merged_df['rouge_l'], errors='coerce').mean()
        else:
            rouge_acc, rouge_sem, mean_rouge = np.nan, np.nan, np.nan

        model_results = {
            "judge_accuracy": judge_acc,
            "judge_sem": judge_sem,
            "recall_accuracy": rouge_acc,
            "recall_sem": rouge_sem,
            "mean_rouge_score": mean_rouge,
            "targets": {"judge": {}, "rouge": {}}
        }

        for col_name, measure_label, _, _, is_entropy in ALL_MEASURES:
            if col_name in merged_df.columns:
                if 'correctness' in merged_df.columns:
                    auroc_j = compute_auroc(merged_df['correctness'].values, merged_df[col_name].values, is_entropy=is_entropy)
                    aurc_j = compute_aurc(merged_df['correctness'].values, merged_df[col_name].values, is_entropy=is_entropy)
                    model_results["targets"]["judge"][measure_label] = {"auroc": auroc_j, "aurc": aurc_j}
                    model_results[measure_label] = {"auroc": auroc_j, "aurc": aurc_j}

                if 'rouge_l_correctness' in merged_df.columns:
                    auroc_r = compute_auroc(merged_df['rouge_l_correctness'].values, merged_df[col_name].values, is_entropy=is_entropy)
                    aurc_r = compute_aurc(merged_df['rouge_l_correctness'].values, merged_df[col_name].values, is_entropy=is_entropy)
                    model_results["targets"]["rouge"][measure_label] = {"auroc": auroc_r, "aurc": aurc_r}

        metrics[mk] = model_results

    return metrics, entropy_bar_stats


def plot_accuracy_comparison_sciq(sciq_metrics, output_file, rouge_threshold=0.25):
    """Plots a single-panel bar chart comparing LLM Judge Accuracy vs. ROUGE-L Accuracy for SciQ Biased Questions."""
    fig, ax = plt.subplots(figsize=(8, 5.5), dpi=300)

    x_labels = [label for _, label, _ in MODEL_ORDER]
    x = np.arange(len(x_labels))
    bar_width = 0.35

    judge_accs = [sciq_metrics.get(m, {}).get('judge_accuracy', np.nan) for m, _, _ in MODEL_ORDER]
    judge_sems = [sciq_metrics.get(m, {}).get('judge_sem', np.nan) for m, _, _ in MODEL_ORDER]

    rouge_accs = [sciq_metrics.get(m, {}).get('recall_accuracy', np.nan) for m, _, _ in MODEL_ORDER]
    rouge_sems = [sciq_metrics.get(m, {}).get('recall_sem', np.nan) for m, _, _ in MODEL_ORDER]

    ax.bar(
        x - bar_width/2, judge_accs, width=bar_width, yerr=judge_sems,
        label="LLM Judge Accuracy", color="#1f77b4", capsize=3.5,
        error_kw={'ecolor': 'black', 'linewidth': 1.2, 'capthick': 1.2}
    )
    ax.bar(
        x + bar_width/2, rouge_accs, width=bar_width, yerr=rouge_sems,
        label=f"ROUGE-L Accuracy (≥{rouge_threshold})", color="#ff7f0e", capsize=3.5,
        error_kw={'ecolor': 'black', 'linewidth': 1.2, 'capthick': 1.2}
    )

    ax.set_xticks(x)
    ax.set_xticklabels(x_labels, rotation=0, fontsize=11)
    ax.set_title("SciQ Accuracy Comparison (Biased Questions)", fontsize=13, pad=12)
    ax.set_ylim(0, 1.05)
    ax.set_ylabel("Accuracy Rate", fontsize=12)
    ax.set_axisbelow(True)
    ax.yaxis.grid(True, linestyle='-', alpha=0.3, color='lightgrey')

    for spine in ['top', 'right', 'left', 'bottom']:
        ax.spines[spine].set_visible(False)

    ax.legend(loc="upper left", frameon=True, facecolor="white", edgecolor="none", fontsize=11)
    plt.tight_layout()
    os.makedirs(os.path.dirname(output_file), exist_ok=True)
    plt.savefig(output_file, bbox_inches='tight')
    plt.close()
    print(f"Saved SciQ Accuracy Bar Chart to: {output_file}")


def plot_entropy_bars_sciq(entropy_bar_stats, output_file):
    """Generates grouped bar chart for entropy measures across models on SciQ Biased Questions."""
    model_order = [
        ("llama3.2_1b", "1B (Llama)"),
        ("qwen3_1.7b", "1.7B (Qwen)"),
        ("llama3.2_3b", "3B (Llama)"),
        ("qwen3_4b", "4B (Qwen)"),
    ]

    labels = [display for _, display in model_order]
    means_per_metric = {m[0]: [] for m in ENTROPY_MEASURES}
    sems_per_metric = {m[0]: [] for m in ENTROPY_MEASURES}

    for model_key, _ in model_order:
        entry = entropy_bar_stats.get(model_key, {})
        for metric_key, _, _, _, _ in ENTROPY_MEASURES:
            mean, sem_val = entry.get(metric_key, (0.0, 0.0))
            means_per_metric[metric_key].append(mean)
            sems_per_metric[metric_key].append(sem_val)

    x = np.arange(len(labels))
    num_metrics = len(ENTROPY_MEASURES)
    bar_width = 0.75 / num_metrics

    fig, ax = plt.subplots(figsize=(9, 5.5), dpi=300)

    for i, (metric_key, metric_label, _, _, _) in enumerate(ENTROPY_MEASURES):
        offset = (i - (num_metrics - 1) / 2) * bar_width
        ax.bar(
            x + offset,
            means_per_metric[metric_key],
            width=bar_width,
            yerr=sems_per_metric[metric_key],
            label=metric_label,
            color=COLORS_BAR[i % len(COLORS_BAR)],
            capsize=3.5,
            error_kw={'ecolor': 'black', 'linewidth': 1.2, 'capthick': 1.2}
        )

    ax.set_ylabel("Uncertainty Score (Entropy)", fontsize=12, labelpad=10)
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=0, fontsize=11)
    ax.set_title("SciQ Entropy Scores by Model (Biased Questions)", fontsize=13, pad=12)
    ax.legend(loc='upper right', frameon=True, facecolor='white', edgecolor='none', fontsize=11)
    ax.yaxis.grid(True, linestyle='-', alpha=0.3, color='lightgrey')

    for spine in ['top', 'right', 'left', 'bottom']:
        ax.spines[spine].set_visible(False)

    plt.tight_layout()
    os.makedirs(os.path.dirname(output_file), exist_ok=True)
    plt.savefig(output_file, bbox_inches='tight')
    plt.close()
    print(f"Saved SciQ Entropy Bar Chart to: {output_file}")


def plot_kuhn_style_sciq(sciq_metrics, metric_type="auroc", target="judge", output_file="figures_sciq_biased/kuhn_plot.png"):
    """Generates single-panel scaling curves for SciQ Biased Questions."""
    fig, ax = plt.subplots(figsize=(8, 5.5), dpi=300)

    target_label = target.upper()
    x_labels = [label for _, label, _ in MODEL_ORDER]
    x_indices = np.arange(len(MODEL_ORDER))

    for col_name, measure_label, marker, color, is_entropy in ALL_MEASURES:
        y_vals = []
        for model_tag, _, _ in MODEL_ORDER:
            val = sciq_metrics.get(model_tag, {}).get("targets", {}).get(target, {}).get(measure_label, {}).get(metric_type, np.nan)
            if np.isnan(val):
                val = sciq_metrics.get(model_tag, {}).get(measure_label, {}).get(metric_type, np.nan)
            y_vals.append(val)

        if not np.all(np.isnan(y_vals)):
            ax.plot(
                x_indices,
                y_vals,
                label=measure_label,
                marker=marker,
                color=color,
                linestyle='--',
                linewidth=1.8,
                markersize=7
            )

