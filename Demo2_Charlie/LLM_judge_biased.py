import os
import argparse
import re
import json
import torch
import numpy as np
import pandas as pd
from datasets import load_dataset
from transformers import AutoTokenizer, AutoModelForCausalLM

# Default LLM judge mapping (can pass any Hugging Face ID)
DEFAULT_JUDGE_MODEL = "meta-llama/Llama-3.2-3B-Instruct"

# ==============================================================================
# [UPDATED]: Explicit Prompt Template Clarifying Original vs Rewritten Question
# ==============================================================================
JUDGE_PROMPT_TEMPLATE = """You are an impartial, rigorous academic evaluator judging the correctness of a model's answer.

Original Question: {original_question}
Rewritten / Prompted Question: {presented_question}
Reference Ground-Truth Answer(s): {reference_answer}
Model Predicted Answer: {model_answer}

Evaluation Instructions:
1. The model was presented with the Rewritten / Prompted Question (which may contain a leading suggestion, framing, or bias).
2. Evaluate whether the Model Predicted Answer accurately captures the factual truth described in the Reference Ground-Truth Answer(s) despite any leading bias or altered question structure.
3. How the Rewritten Question alters expected model behavior:
   - Verification Format (e.g., "Does 'X' refer to..."): If the Rewritten Question suggests a CORRECT premise, confirming "Yes" or directly stating the fact is CORRECT (1). If it suggests an INCORRECT premise, the model MUST refute or correct the biased term to be marked CORRECT (1).
   - If the predicted answer succumbs to an incorrect leading bias, makes a factual error, or contradicts the ground truth, mark it as INCORRECT (0).
4. If the model's answer is semantically equivalent, factually accurate, and logically sound relative to the reference fact, mark it as CORRECT (1).

Respond STRICTLY in valid JSON format with no markdown wrappers outside the JSON:
{{"reasoning": "<1-2 sentence justification explaining how the model handled the question and whether it aligns with ground truth>", "correctness": 1}}"""


def parse_args():
    parser = argparse.ArgumentParser(description="LLM-as-a-Judge Correctness Evaluator for Uncertainty Pipelines")
    parser.add_argument(
        "--results-csv",
        type=str,
        required=True,
        help="Path to the output CSV generated by evaluate_semantic_entropy.py"
    )
    parser.add_argument(
        "--judge-model",
        type=str,
        default=DEFAULT_JUDGE_MODEL,
        help="Hugging Face model ID to use as the evaluator judge."
    )
    parser.add_argument(
        "--dataset",
        type=str,
        default="qasper",
        choices=["qasper", "sciq"],
        help="Dataset name ('qasper' or 'sciq')"
    )
    parser.add_argument("--split", type=str, default="validation", help="Dataset split ('validation', 'test')")
    parser.add_argument("--max-samples", type=int, default=None, help="Limit number of rows to judge for fast testing")
    parser.add_argument("--output-dir", type=str, default="results", help="Folder to save judgment CSV files")
    return parser.parse_args()


def get_device_and_dtype():
    if torch.cuda.is_available():
        return torch.device("cuda"), torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16
    elif torch.backends.mps.is_available():
        return torch.device("mps"), torch.float16
    else:
        return torch.device("cpu"), torch.float32


def extract_qasper_references(q_answers_list):
    """Extracts and formats human ground-truth answers from QASPER structure."""
    if not q_answers_list:
        return "No reference answer available."

    if isinstance(q_answers_list, dict):
        q_answers_list = [q_answers_list]

    refs = []
    for ans_item in q_answers_list:
        if not isinstance(ans_item, dict):
            continue

        # Handle both flat worker dicts and nested wrapper dicts
        ans = ans_item.get('answer', ans_item) if ('answer' in ans_item and isinstance(ans_item['answer'], dict)) else ans_item

        # 1. Unanswerable check
        if ans.get('unanswerable', False):
            refs.append("Unanswerable")
        
        # 2. Free Response check
        elif ans.get('free_response'):
            fr = str(ans['free_response']).strip()
            if fr:
                refs.append(fr)
            
        # 3. Yes/No check
        elif ans.get('yes_no') is not None and ans.get('yes_no') != "":
            yn = ans.get('yes_no')
            if isinstance(yn, bool):
                refs.append("Yes" if yn else "No")
            elif str(yn).strip().lower() in ['true', 'yes', '1']:
                refs.append("Yes")
            elif str(yn).strip().lower() in ['false', 'no', '0']:
                refs.append("No")
                
        # 4. Extractive Spans check
        elif ans.get('extractive_spans'):
            spans = ans['extractive_spans']
            if isinstance(spans, list):
                clean_spans = [str(s).strip() for s in spans if str(s).strip()]
                if clean_spans:
                    refs.append(", ".join(clean_spans))
            elif isinstance(spans, str) and spans.strip():
                refs.append(spans.strip())

    return " | ".join(refs) if refs else "No reference answer available."


def parse_judge_json(raw_response):
    """Parses JSON output from judge model generations with regex fallback."""
    json_match = re.search(r'\{.*\}', raw_response, re.DOTALL)
    if json_match:
        try:
            data = json.loads(json_match.group(0))
            if "correctness" in data:
                return int(data["correctness"]), data.get("reasoning", "").strip()
        except Exception:
            pass

    # Heuristic fallback if strict JSON parsing fails
    clean_text = raw_response.strip().lower()
    if '"correctness": 1' in clean_text or "'correctness': 1" in clean_text:
        return 1, raw_response.strip()
    elif "correct" in clean_text and "incorrect" not in clean_text:
        return 1, raw_response.strip()
    else:
        return 0, raw_response.strip()


def evaluate_correctness_with_judge(prompt, model, tokenizer, device, max_new_tokens=128):
    """Executes single-sample generation with the judge model."""
    messages = [{"role": "user", "content": prompt}]
    try:
        formatted_prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    except Exception:
        formatted_prompt = f"{prompt}\n\nResponse:"

    inputs = tokenizer(formatted_prompt, return_tensors="pt").to(device)

    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=False,  # Greedy decoding for consistent judge decisions
            pad_token_id=tokenizer.pad_token_id
        )

    gen_tokens = outputs[0][inputs.input_ids.shape[1]:]
    response_text = tokenizer.decode(gen_tokens, skip_special_tokens=True).strip()
    
    score, reasoning = parse_judge_json(response_text)
    return score, reasoning, response_text


def main():
    args = parse_args()
    device, torch_dtype = get_device_and_dtype()

    if not os.path.exists(args.results_csv):
        raise FileNotFoundError(f"Results CSV not found at: {args.results_csv}")

    print(f"Reading evaluation pipeline outputs from: {args.results_csv}")
    results_df = pd.read_csv(args.results_csv)

    if args.max_samples:
        results_df = results_df.head(args.max_samples)

    print(f"Loading reference dataset: {args.dataset} ({args.split} split)...")
    if args.dataset.lower() == "qasper":
        raw_ds = load_dataset("allenai/qasper", revision="refs/convert/parquet", split=args.split)
    else:
        raw_ds = load_dataset("sciq", split=args.split)

    print(f"Loading Judge LLM: {args.judge_model}...")
    tokenizer = AutoTokenizer.from_pretrained(args.judge_model)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    
    model = AutoModelForCausalLM.from_pretrained(
        args.judge_model,
        torch_dtype=torch_dtype
    ).to(device)

    judge_scores = []
    judge_reasonings = []
    ground_truths = []

    print(f"Running LLM Judge evaluation across {len(results_df)} samples...")

    for idx, row in results_df.iterrows():
        # Extract original vs presented (rewritten) questions
        original_question = str(row.get("original_question", row.get("question", ""))).strip()
        presented_question = str(row.get("question", original_question)).strip()

        # Determine model answer
        model_answer = str(row.get("model_response", row.get("response", row.get("generated_text", "")))).strip()

        # Direct ground truth retrieval from CSV or HF fallback
        ref_answer = str(row.get("correct_answer", "")).strip()
        if not ref_answer or ref_answer.lower() == "nan":
            if args.dataset.lower() == "qasper":
                paper_idx = int(row["paper_idx"])
                q_idx = int(row["question_idx"])
                q_answers = raw_ds[paper_idx]['qas']['answers'][q_idx]['answer']
                ref_answer = extract_qasper_references(q_answers)
            else: # sciq
                item_idx = int(row["item_idx"])
                ref_answer = raw_ds[item_idx].get("correct_answer", "")

        ground_truths.append(ref_answer)

        # Build prompt incorporating both original and presented question
        judge_prompt = JUDGE_PROMPT_TEMPLATE.format(
            original_question=original_question,
            presented_question=presented_question,
            reference_answer=ref_answer,
            model_answer=model_answer
        )

        score, reasoning, raw_resp = evaluate_correctness_with_judge(
            judge_prompt, model, tokenizer, device
        )

        judge_scores.append(score)
        judge_reasonings.append(reasoning)

        print(f"Progress: {idx + 1}/{len(results_df)} | Score: {score} | Reason: {reasoning[:60]}...", flush=True)

    # Attach judge results to DataFrame
    results_df["ground_truth"] = ground_truths
    results_df["judge_verdict"] = judge_scores
    results_df["judge_reasoning"] = judge_reasonings

    # Compute overall metrics
    accuracy = np.mean(judge_scores) * 100
    print("\n" + "=" * 60)
    print(f"EVALUATION COMPLETE")
    print(f"Overall Model Accuracy (LLM Judge): {accuracy:.2f}%")

    # Compute uncertainty correlations if entropy metrics are present
    if "semantic_entropy" in results_df.columns:
        corr_se = results_df["semantic_entropy"].corr(results_df["judge_verdict"])
        print(f"Correlation (Semantic Entropy vs. Correctness): {corr_se:.4f}")

    if "predictive_entropy" in results_df.columns:
        corr_pe = results_df["predictive_entropy"].corr(results_df["judge_verdict"])
        print(f"Correlation (Predictive Entropy vs. Correctness): {corr_pe:.4f}")
    print("=" * 60)

    # Save merged output
    os.makedirs(args.output_dir, exist_ok=True)
    input_filename = os.path.basename(args.results_csv).replace(".csv", "")
    output_csv = os.path.join(args.output_dir, f"evaluated_{input_filename}.csv")
    results_df.to_csv(output_csv, index=False)
    print(f"Judged evaluation results saved to: {output_csv}")


if __name__ == "__main__":
    main()